#!/usr/bin/env python3
"""Moves PopBoard's border-radius declarations onto the squircle scale in public/shared/corners/corners.css.
Idempotent: a migrated declaration is recognised and left alone. Prints a tally of migrated vs left.
--write applies it, --check fails if any file still needs it (tests/corners.test.mjs).
Scope: .css files and <style> blocks in .html. Not touched: style="" attributes, radii set from JS,
circles (%), pills (>= 40px), radii under 6px, elliptical "a / b" radii, calc()/vw values.
Those get `corner-shape: round; --sq: 0` so a squircle from a broader rule cannot leak onto them."""
import re, sys, json
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parents[2] / "public"
SKIP_DIRS = {"vendor", "corners", "geometry"}  # geometry is off the site and generated by tools/geometry
MIN, PILL = 6, 40
DECL = re.compile(r'(?<![\w-])border-radius(\s*:\s*)([^;{}"]+?)(\s*(?:!important)?\s*)(?=;|}|$)', re.M)
PXV = re.compile(r'^(\d*\.?\d+)px$')
tally, left, files_changed = Counter(), Counter(), []

def all_var_defs():
    defs = {}
    for p in list(ROOT.rglob("*.css")) + list(ROOT.rglob("*.html")):
        if SKIP_DIRS & set(p.relative_to(ROOT).parts): continue
        for m in re.finditer(r'(--[\w-]+)\s*:\s*([^;}{]+)', p.read_text(errors="ignore")):
            defs.setdefault(m.group(1), set()).add(m.group(2).strip())
    return defs
VDEFS = all_var_defs()

def var_ok(name):
    vals = VDEFS.get(name)
    if not vals: return False
    for v in vals:
        if v in ("0", "0px"): continue
        m = PXV.match(v)
        if not m or not (MIN <= float(m.group(1)) < PILL): return False
    return True

def token(px):
    n = float(px)
    if n < MIN: return f"{px}px" if n else "0"
    return f"var(--r-{px}, {px}px)" if n == int(n) else None

def convert(val):
    v = val.strip()
    if "--sq-fit" in v: return None, "already"
    if v == "inherit": return None, "inherit"
    if "/" in v: return None, "elliptical"
    parts = v.split()
    m = re.fullmatch(r'var\((--[\w-]+)\)', v)
    if m:
        if var_ok(m.group(1)): return f"calc({v} * var(--sq-k, 1) * var(--sq-fit, 1))", "var"
        return None, "var-other"
    if not 1 <= len(parts) <= 4: return None, "other"
    nums = []
    for p in parts:
        if p == "0": nums.append(0.0); continue
        mm = PXV.match(p)
        if mm: nums.append(float(mm.group(1))); continue
        if p.endswith("%"): return None, "percent"
        if re.fullmatch(r'\d*\.?\d+(cqw|cqi|em|rem)', p): nums.append(None); continue
        return None, "unit"
    if None in nums:
        # Scale-relative radii (slide stages in cqw, em boxes): same rule, scaled at use. corners.js skips any under 6px.
        return " ".join("0" if p == "0" else f"calc({p} * var(--sq-k, 1) * var(--sq-fit, 1))" for p in parts), "relative"
    if max(nums) >= PILL: return None, "pill"
    if max(nums) < MIN: return None, "tiny"
    toks = [token(p if p == "0" else PXV.match(p).group(1)) for p in parts]
    if None in toks: return None, "fractional"
    if len(set(toks)) == 1: toks = toks[:1]
    # Each real corner is scaled by the fit factor (Safari path); 0 and tiny corners stay as they are.
    return " ".join(t if not t.startswith("var(") else f"calc({t} * var(--sq-fit, 1))" for t in toks), "px"

def migrate_css(text):
    def rep(m):
        new, why = convert(m.group(2))
        if new is None:
            if why == "already" or re.match(r'\s*;\s*corner-shape', m.string[m.end():]): tally["already"] += 1; return m.group(0)
            left[why] += 1
            if m.group(2).strip() == "inherit": return m.group(0) + "; corner-shape: inherit"
            # Circles, pills, tiny radii: say so, so a squircle from a broader rule on the same box cannot leak in.
            return m.group(0) + "; corner-shape: round; --sq: 0"
        tally[why] += 1
        return f"border-radius{m.group(1)}{new}{m.group(3)}; corner-shape: squircle; --sq: 1"
    return DECL.sub(rep, text)

def main(write):
    for p in sorted(ROOT.rglob("*")):
        rel = p.relative_to(ROOT)
        if SKIP_DIRS & set(rel.parts) or rel.name.startswith("study-geometry") or p.suffix not in (".css", ".html"): continue
        s = p.read_text(errors="ignore")
        if p.suffix == ".css": out = migrate_css(s)
        else: out = re.sub(r'(<style[^>]*>)(.*?)(</style>)', lambda m: m.group(1) + migrate_css(m.group(2)) + m.group(3), s, flags=re.S)
        if out != s:
            files_changed.append(str(rel))
            if write: p.write_text(out)
    print(json.dumps({"migrated": dict(tally), "left": dict(left), "files": len(files_changed)}, indent=1))
    if "--check" in sys.argv and files_changed:
        print("not migrated:", *files_changed, sep="\n  "); sys.exit(1)

if __name__ == "__main__": main("--write" in sys.argv)

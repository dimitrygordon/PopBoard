// Glasses: Tap to switch eyes and lenses.
import { calc, f2 } from "../kit.js";
const F = f2, E = (x, d = 2) => x.toExponential(d).replace(/e\+?(-?)(\d+)/, (_, s, p) => " \u00d7 10^" + (s ? "\u2212" : "") + p).replace("-", "\u2212"), R = (a) => a[Math.floor(Math.random() * a.length)];
export default function build(ctx) {
  const k = calc(ctx, {
    st: { i: 0, N: ["nearsighted + concave lens: focus moves back onto the retina", "farsighted + convex lens: focus moves forward onto the retina", "nearsighted + convex lens: worse, focus even farther in front"] },
    sliders: [],
    cuts: [
    { id: "try", label: "Eye: tap for the next combination", tap: (st, c) => { st.i = (st.i + 1) % 3; return ""; } }],
    show: (st) => st.N[st.i],
  });
  ctx.art.touchable(["try"]);
  return { destroy() {} };
}

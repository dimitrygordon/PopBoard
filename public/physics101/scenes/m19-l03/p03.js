// Predictions: Tap to cycle predictions, then compare with the real result.
import { calc, f2 } from "../kit.js";
const F = f2, E = (x, d = 2) => x.toExponential(d).replace(/e\+?(-?)(\d+)/, (_, s, p) => " \u00d7 10^" + (s ? "\u2212" : "") + p).replace("-", "\u2212"), R = (a) => a[Math.floor(Math.random() * a.length)];
export default function build(ctx) {
  const k = calc(ctx, {
    st: { i: 0, N: ["prediction 1: the first lamp is brighter", "prediction 2: the second lamp is brighter", "prediction 3: they're equally bright", "result: equally bright, same current"] },
    sliders: [],
    cuts: [
    { id: "try", label: "Circuit: tap for the next one", tap: (st, c) => { st.i = (st.i + 1) % 4; return ""; } }],
    show: (st) => st.N[st.i],
  });
  ctx.art.touchable(["try"]);
  return { destroy() {} };
}

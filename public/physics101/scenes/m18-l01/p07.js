// Rub pairs: Tap to rub the next pair of materials.
import { calc, f2 } from "../kit.js";
const F = f2, E = (x, d = 2) => x.toExponential(d).replace(/e\+?(-?)(\d+)/, (_, s, p) => " \u00d7 10^" + (s ? "\u2212" : "") + p).replace("-", "\u2212"), R = (a) => a[Math.floor(Math.random() * a.length)];
export default function build(ctx) {
  const k = calc(ctx, {
    st: { i: 0, N: ["rubber rod + fur: rod \u2212, fur +", "glass rod + silk: glass +, silk \u2212", "balloon + hair: balloon \u2212, hair +"] },
    sliders: [],
    cuts: [
    { id: "try", label: "Materials: tap for the next pair", tap: (st, c) => { st.i = (st.i + 1) % 3; return ""; } }],
    show: (st) => st.N[st.i],
  });
  ctx.art.touchable(["try"]);
  return { destroy() {} };
}
